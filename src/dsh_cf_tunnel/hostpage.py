"""The generated dsh patch that marks the tunneled page as host-owned."""

from __future__ import annotations

import os

from .log import LOGGER

# A `dsh --patch` overlay that makes the tunneled page count as host-owned. The
# browser client reads `globalThis.__DSH_TRANSPORT__.ownsHost` before it looks at
# the page hostname, and keeps the Settings and Models pages unavailable unless
# the page counts as loopback; a tunneled page never is. This publishes the same
# flag the desktop shell sets for its own pages, so those pages load remotely too.
HOST_PAGE_PLUGIN = """\
/**
 * Mark the served page as host-owned.
 *
 * A page served through a tunnel is never a loopback page, so the client would
 * keep its settings surfaces unavailable. Publishing the host-owned transport
 * flag is what the desktop shell does for the pages it serves itself.
 */
export const name = "dsh-server-host-page";

/** Publish the host-owned transport flag into every served index page. */
export function apply(ctx) {
    ctx.on("webserver/index-inject", (table) => {
        table.push({
            kind: "global",
            name: "__DSH_TRANSPORT__",
            value: { ownsHost: true }
        });
    });
}
"""


HOST_PAGE_PATCH = """\
# Generated by dsh-cf-tunnel: one insert over the profile tree carrying the
# host-owned page flag the tunneled Web UI needs for its settings pages.
- insert:
    - id: dsh-server-host-page
      name: ./dsh-server-host-page.js
"""


HOST_PAGE_PLUGIN_FILE = "dsh-server-host-page.js"


HOST_PAGE_PATCH_FILE = "patch.yml"


def write_host_page_patch(directory: str) -> str:
    """Write the host-owned page patch into a directory and return its path.

    The row's relative plugin path is anchored beside the patch file, so both
    files must stay together.
    """
    os.makedirs(directory, exist_ok=True)
    plugin = os.path.join(directory, HOST_PAGE_PLUGIN_FILE)
    with open(plugin, "w", encoding="utf-8") as stream:
        stream.write(HOST_PAGE_PLUGIN)
    patch = os.path.join(directory, HOST_PAGE_PATCH_FILE)
    with open(patch, "w", encoding="utf-8") as stream:
        stream.write(HOST_PAGE_PATCH)
    LOGGER.debug("wrote the host-owned page patch to %s", patch)
    return patch
